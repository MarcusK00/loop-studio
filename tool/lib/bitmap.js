function hexToRgba(hex) {
  const clean = String(hex || "#000000").replace("#", "");
  if (clean.length === 3) {
    return [
      parseInt(clean[0] + clean[0], 16),
      parseInt(clean[1] + clean[1], 16),
      parseInt(clean[2] + clean[2], 16),
      255
    ];
  }
  return [
    parseInt(clean.slice(0, 2), 16) || 0,
    parseInt(clean.slice(2, 4), 16) || 0,
    parseInt(clean.slice(4, 6), 16) || 0,
    255
  ];
}

export class BitmapBuffer {
  constructor(width, height) {
    this.width = Math.max(1, Math.round(width));
    this.height = Math.max(1, Math.round(height));
    this.data = new Uint8ClampedArray(this.width * this.height * 4);
  }

  fillRect(x, y, w, h, hex, alpha = 1) {
    const [r, g, b] = hexToRgba(hex);
    const x0 = Math.max(0, Math.floor(x));
    const y0 = Math.max(0, Math.floor(y));
    const x1 = Math.min(this.width, Math.ceil(x + w));
    const y1 = Math.min(this.height, Math.ceil(y + h));
    const a = Math.max(0, Math.min(1, alpha));
    const inv = 1 - a;

    for (let py = y0; py < y1; py++) {
      const row = py * this.width;
      for (let px = x0; px < x1; px++) {
        const idx = (row + px) * 4;
        if (a >= 0.999) {
          this.data[idx] = r;
          this.data[idx + 1] = g;
          this.data[idx + 2] = b;
          this.data[idx + 3] = 255;
        } else {
          this.data[idx] = Math.round(this.data[idx] * inv + r * a);
          this.data[idx + 1] = Math.round(this.data[idx + 1] * inv + g * a);
          this.data[idx + 2] = Math.round(this.data[idx + 2] * inv + b * a);
          this.data[idx + 3] = 255;
        }
      }
    }
  }

  strokeRect(x, y, w, h, hex, thickness = 1) {
    const t = Math.max(1, Math.round(thickness));
    this.fillRect(x, y, w, t, hex);
    this.fillRect(x, y + h - t, w, t, hex);
    this.fillRect(x, y, t, h, hex);
    this.fillRect(x + w - t, y, t, h, hex);
  }

  drawText(text, x, y, hex, scale = 1.5) {
    const str = String(text || "").toUpperCase();
    const s = Math.max(1, Math.round(scale));
    let cx = Math.round(x);
    const cy = Math.round(y);

    for (let i = 0; i < str.length; i++) {
      const glyph = FONT_5X7[str[i]] || FONT_5X7[" "];
      for (let col = 0; col < 5; col++) {
        const bits = glyph[col];
        for (let row = 0; row < 7; row++) {
          if ((bits >> row) & 1) {
            this.fillRect(cx + col * s, cy + row * s, s, s, hex);
          }
        }
      }
      cx += 6 * s;
    }
  }
}
